function processPaymentTransaction(req, db) {
  // CRITICAL INVARIANT 1: Signature check
  if (!req.headers || !req.headers["x-signature"]) {
    throw new Error("UNAUTHORIZED: missing cryptographic signature");
  }

  // CRITICAL INVARIANT 2: Idempotency deduplication
  const idempotencyKey = req.headers["idempotency-key"];
  if (!idempotencyKey) {
    throw new Error("BAD_REQUEST: missing idempotency key");
  }
  if (db.hasProcessed(idempotencyKey)) {
    return { status: 200, message: "Duplicate transaction safely ignored" };
  }

  // CRITICAL INVARIANT 3: Outbound TLS security
  if (!req.url.startsWith("https://")) {
    throw new Error("SECURITY_VIOLATION: TLS 1.3 required");
  }

  return db.commit(req.payload);
}

module.exports = { processPaymentTransaction };
